import { z } from "zod";
import { playerResponseSchema } from "@/lib/schemas";
import { fetchPlayer } from "@/lib/page";
import { buildSabrSession } from "@/lib/sabr";
import type { SabrSession } from "@/lib/sabr";
import { parseUrl } from "@/lib/url";
import type { StreamFormat, Thumbnail } from "@/lib/schemas";

type PlayerResponse = z.infer<typeof playerResponseSchema>;

const DATE_LENGTH = 10;
const WATCH_HOSTS = new Set(["www.youtube.com", "youtube.com", "m.youtube.com", "music.youtube.com"]);
const VIDEO_ID_PATTERN = /^[\w-]{11}$/;
const SHORT_URL_PATH_PATTERN = /^\/(?:shorts|embed|live|v)\/([\w-]{11})/;
const VISITOR_DATA_PATTERN = /"VISITOR_DATA":"([^"]+)"/;
const INNERTUBE_PLAYER_URL = "https://www.youtube.com/youtubei/v1/player";
const YOUTUBE_HOME_URL = "https://www.youtube.com/";
const YOUTUBE_ORIGIN = "https://www.youtube.com";
const CDN_ORIGIN_RULE_ID = 1;
const PLAYER_HEADERS_RULE_ID = 2;
const PLAYER_URL_FILTER = "||www.youtube.com/youtubei/v1/player";
const ANDROID_VR_CLIENT_NAME_ID = "28";
const GOOGLEVIDEO_URL_FILTER = "*.googlevideo.com/videoplayback*";

const ANDROID_VR_CLIENT = {
  clientName: "ANDROID_VR",
  clientVersion: "1.62.27",
  deviceMake: "Oculus",
  deviceModel: "Quest 3",
  androidSdkVersion: 32,
  userAgent: "com.google.android.apps.youtube.vr.oculus/1.62.27 (Linux; U; Android 12L; eureka-user Build/SQ3A.220605.009.A1) gzip",
  osName: "Android",
  osVersion: "12L",
  hl: "en",
  gl: "US"
};

export type CaptionOption = {
  languageCode: string;
  label: string;
  url: string;
  isAutoGenerated: boolean;
  text?: string;
};

export type ResolvedVideo = {
  id: string;
  title: string;
  uploader: string;
  channelId: string;
  description: string;
  durationSeconds: number;
  viewCount: number;
  tags: string[];
  category: string;
  isLive: boolean;
  uploadDate: string;
  thumbnails: Thumbnail[];
  formats: StreamFormat[];
  captions: CaptionOption[];
  sabr?: SabrSession;
};

export class BotCheckError extends Error {}

export function parseVideoId(input: string) {
  const trimmed = input.trim();
  if (VIDEO_ID_PATTERN.test(trimmed)) {
    return trimmed;
  }

  const url = parseUrl(trimmed);
  if (!url) {
    return null;
  }

  if (url.hostname === "youtu.be") {
    return url.pathname.slice(1, 12) || null;
  }

  if (!WATCH_HOSTS.has(url.hostname)) {
    return null;
  }

  return url.searchParams.get("v") ?? url.pathname.match(SHORT_URL_PATH_PATTERN)?.[1] ?? null;
}

const BARE_PLAYLIST_ID_PATTERN = /^(?:PL|UU|LL|WL|OLAK5uy_|FL)[\w-]*$/;

export function parsePlaylistId(input: string) {
  const trimmed = input.trim();
  if (BARE_PLAYLIST_ID_PATTERN.test(trimmed)) {
    return trimmed;
  }

  const url = parseUrl(trimmed);
  if (!url || !WATCH_HOSTS.has(url.hostname)) {
    return null;
  }

  return url.searchParams.get("list");
}

const YOUTUBE_ORIGIN_HEADERS = [
  { header: "Origin", operation: "set", value: YOUTUBE_ORIGIN },
  { header: "Referer", operation: "set", value: `${YOUTUBE_ORIGIN}/` },
  { header: "Sec-Fetch-Site", operation: "set", value: "cross-site" }
] satisfies Browser.declarativeNetRequest.ModifyHeaderInfo[];

const BROWSER_FINGERPRINT_HEADERS = ["sec-ch-ua", "sec-ch-ua-mobile", "sec-ch-ua-platform", "sec-fetch-dest", "sec-fetch-mode", "sec-fetch-site"];

const PLAYER_HEADERS = [
  { header: "Origin", operation: "set", value: YOUTUBE_ORIGIN },
  ...BROWSER_FINGERPRINT_HEADERS.map(header => ({ header, operation: "remove" }) as const),
  { header: "User-Agent", operation: "set", value: ANDROID_VR_CLIENT.userAgent },
  { header: "X-YouTube-Client-Name", operation: "set", value: ANDROID_VR_CLIENT_NAME_ID },
  { header: "X-YouTube-Client-Version", operation: "set", value: ANDROID_VR_CLIENT.clientVersion }
] satisfies Browser.declarativeNetRequest.ModifyHeaderInfo[];

function buildHeaderRule(id: number, urlFilter: string, requestHeaders: Browser.declarativeNetRequest.ModifyHeaderInfo[]) {
  return {
    id,
    action: { type: "modifyHeaders", requestHeaders },
    condition: { urlFilter, initiatorDomains: [browser.runtime.id] }
  } satisfies Browser.declarativeNetRequest.Rule;
}

export async function registerRequestHeaderRules() {
  await browser.declarativeNetRequest.updateSessionRules({
    removeRuleIds: [CDN_ORIGIN_RULE_ID, PLAYER_HEADERS_RULE_ID],
    addRules: [
      buildHeaderRule(CDN_ORIGIN_RULE_ID, GOOGLEVIDEO_URL_FILTER, YOUTUBE_ORIGIN_HEADERS),
      buildHeaderRule(PLAYER_HEADERS_RULE_ID, PLAYER_URL_FILTER, PLAYER_HEADERS)
    ]
  });
}

async function fetchVisitorData() {
  const html = await (await fetch(YOUTUBE_HOME_URL)).text();
  const visitorData = html.match(VISITOR_DATA_PATTERN)?.[1];
  if (!visitorData) {
    throw new Error("Couldn't read visitor data from youtube.com");
  }

  return visitorData;
}

async function fetchPlayerResponse(videoId: string) {
  const visitorData = await fetchVisitorData();
  const response = await fetch(INNERTUBE_PLAYER_URL, {
    method: "POST",
    credentials: "omit",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      context: { client: { ...ANDROID_VR_CLIENT, visitorData } },
      videoId,
      contentCheckOk: true,
      racyCheckOk: true
    })
  });
  if (!response.ok) {
    throw new Error(`Player request failed: HTTP ${response.status} ${(await response.text()).slice(0, 300)}`);
  }

  const parsed = playerResponseSchema.safeParse(await response.json());
  if (!parsed.success) {
    throw new Error(`YouTube sent a player response in an unexpected shape: ${z.prettifyError(parsed.error)}`);
  }

  const playerResponse = parsed.data;
  const { status, reason } = playerResponse.playabilityStatus ?? {};
  if (status === "LOGIN_REQUIRED") {
    throw new BotCheckError(`YouTube is asking this connection to confirm it isn't a bot (${reason ?? "sign-in required"}). Signing in doesn't help here, try again later or from another network`);
  }

  if (status !== "OK") {
    throw new Error(`Video isn't playable: ${status} ${reason ?? ""}`);
  }

  return playerResponse;
}

function toVttUrl(baseUrl: string) {
  const url = new URL(baseUrl);
  url.searchParams.set("fmt", "vtt");
  return url.href;
}

function toResolvedVideo(videoId: string, playerResponse: PlayerResponse, formats: StreamFormat[], captionTexts: Record<string, string> = {}): ResolvedVideo {
  const details = playerResponse.videoDetails ?? {};
  const captionTracks = playerResponse.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
  return {
    id: videoId,
    title: details.title ?? videoId,
    uploader: details.author ?? "",
    channelId: details.channelId ?? "",
    description: details.shortDescription ?? "",
    durationSeconds: Number(details.lengthSeconds) || 0,
    viewCount: Number(details.viewCount) || 0,
    tags: details.keywords ?? [],
    category: playerResponse.microformat?.playerMicroformatRenderer?.category ?? "",
    isLive: details.isLive ?? false,
    uploadDate: (playerResponse.microformat?.playerMicroformatRenderer?.uploadDate ?? "").slice(0, DATE_LENGTH).replaceAll("-", ""),
    thumbnails: [...(details.thumbnail?.thumbnails ?? [])].sort((first, second) => first.width - second.width),
    formats,
    captions: captionTracks.map(track => ({
      languageCode: track.languageCode,
      label: track.name?.simpleText ?? track.languageCode,
      url: toVttUrl(track.baseUrl),
      isAutoGenerated: track.kind === "asr",
      text: captionTexts[track.baseUrl] || undefined
    }))
  };
}

export async function resolveVideo(videoId: string) {
  const playerResponse = await fetchPlayerResponse(videoId);
  const { adaptiveFormats = [] } = playerResponse.streamingData ?? {};
  return toResolvedVideo(videoId, playerResponse, adaptiveFormats.filter(format => format.url));
}

export async function resolveVideoFromPage(tabId: number | undefined, videoId: string, withCaptions: boolean) {
  const { playerResponse, requests, captionTexts } = await fetchPlayer(tabId, videoId, withCaptions);
  const parsed = playerResponseSchema.safeParse(playerResponse);
  if (!parsed.success) {
    throw new Error(`The video page sent a player response in an unexpected shape: ${z.prettifyError(parsed.error)}`);
  }

  const { status, reason } = parsed.data.playabilityStatus ?? {};
  if (status !== "OK") {
    throw new Error(`Video isn't playable: ${status} ${reason ?? ""}`);
  }

  const { adaptiveFormats = [] } = parsed.data.streamingData ?? {};
  return { ...toResolvedVideo(videoId, parsed.data, adaptiveFormats, captionTexts), sabr: buildSabrSession(requests, adaptiveFormats) };
}
