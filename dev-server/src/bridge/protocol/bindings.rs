//! The TypeScript declarations of the wire types under `bindings/`, the single source the launcher
//! types its side of the bridge with. `cargo test` regenerates them; a run that finds the committed
//! files stale rewrites them and fails, so the change gets reviewed and committed.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use serde_json::Value;
use ts_rs::{Config, ExportError, TS};

use crate::bridge::protocol::{
    ChangedOutputs, EntrypointLayout, HostRequest, HtmlEntrypoint, InboundMessage, LogLine,
    Notification, OutboundMessage, RebuildHmrResult, ReloadExtensionParams, RequestEnvelope,
    Response, SidecarConfig,
};
use crate::error::Result;
use crate::types::{BrowserKind, Port, RelPath, RequestId};

const BARREL_FILE_NAME: &str = "index.ts";
const BARREL_HEADER: &str =
    "// Generated by `cargo test` in dev-server from the wire types; do not edit this file manually";
const IMPORT_EXTENSION: &str = "ts";
/// JSON numbers are plain doubles, and every 64-bit integer on the wire (ids, epoch milliseconds,
/// intervals) stays far below 2^53, so none of them is a `bigint`.
const LARGE_INT_TYPE: &str = "number";

/// One exported type: its TypeScript name, where its file goes, and how to write it.
struct Binding {
    name: fn(&Config) -> String,
    output_path: fn() -> Option<PathBuf>,
    export: fn(&Config) -> std::result::Result<(), ExportError>,
}

fn binding<T: TS + 'static>() -> Binding {
    Binding {
        name: T::name,
        output_path: T::output_path,
        export: T::export_all,
    }
}

fn bindings() -> [Binding; 18] {
    [
        binding::<BrowserKind>(),
        binding::<Port>(),
        binding::<RelPath>(),
        binding::<RequestId>(),
        binding::<Value>(),
        binding::<HtmlEntrypoint>(),
        binding::<SidecarConfig>(),
        binding::<ChangedOutputs>(),
        binding::<EntrypointLayout>(),
        binding::<ReloadExtensionParams>(),
        binding::<RebuildHmrResult>(),
        binding::<HostRequest>(),
        binding::<RequestEnvelope>(),
        binding::<LogLine>(),
        binding::<OutboundMessage>(),
        binding::<Response>(),
        binding::<Notification>(),
        binding::<InboundMessage>(),
    ]
}

/// `export type { Name } from "./Name.ts";` for every binding, so the launcher imports one module.
fn barrel(config: &Config) -> String {
    let mut lines: Vec<String> = bindings()
        .iter()
        .filter_map(|binding| {
            let path = (binding.output_path)()?;
            let module = path.to_string_lossy().replace('\\', "/");
            Some(format!(
                "export type {{ {} }} from \"./{module}\";",
                (binding.name)(config)
            ))
        })
        .collect();
    lines.sort();
    format!("{BARREL_HEADER}\n\n{}\n", lines.join("\n"))
}

/// Every file under `root`, keyed by its forward-slash path relative to `root`.
fn read_tree(root: &Path) -> Result<BTreeMap<String, String>> {
    let mut files = BTreeMap::new();
    let mut pending = vec![root.to_path_buf()];
    while let Some(directory) = pending.pop() {
        let Ok(entries) = fs::read_dir(&directory) else {
            continue;
        };
        for entry in entries {
            let path = entry?.path();
            if path.is_dir() {
                pending.push(path);
                continue;
            }
            let Ok(relative) = path.strip_prefix(root) else {
                continue;
            };
            let key = relative.to_string_lossy().replace('\\', "/");
            files.insert(key, fs::read_to_string(&path)?);
        }
    }
    Ok(files)
}

fn generate(directory: &Path) -> Result<BTreeMap<String, String>> {
    if directory.exists() {
        fs::remove_dir_all(directory)?;
    }
    let config = Config::new()
        .with_out_dir(directory)
        .with_large_int(LARGE_INT_TYPE)
        .with_import_extension(Some(IMPORT_EXTENSION));
    for binding in bindings() {
        (binding.export)(&config).map_err(std::io::Error::other)?;
    }
    fs::write(directory.join(BARREL_FILE_NAME), barrel(&config))?;
    read_tree(directory)
}

#[test]
fn the_committed_bindings_match_the_wire_types() -> Result<()> {
    let committed_directory = Path::new(env!("CARGO_MANIFEST_DIR")).join("bindings");
    let scratch =
        std::env::temp_dir().join(format!("ytdl-dev-hot-bindings-{}", std::process::id()));
    let fresh = generate(&scratch)?;
    fs::remove_dir_all(&scratch)?;
    let committed = read_tree(&committed_directory)?;
    if committed == fresh {
        return Ok(());
    }
    generate(&committed_directory)?;
    panic!(
        "bindings/ was stale and has been regenerated from the wire types - review and commit it"
    );
}
